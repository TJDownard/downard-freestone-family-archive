def connected(root):
    adjacency = {key:set() for key in people}
    for (a,b,_),edge in edges.items():
        if edge.get('status') != 'Unverified':
            adjacency[a].add(b)
            adjacency[b].add(a)
    seen=set()
    pending=[root]
    while pending:
        key=pending.pop()
        if key not in seen:
            seen.add(key)
            pending.extend(adjacency[key]-seen)
    return seen

