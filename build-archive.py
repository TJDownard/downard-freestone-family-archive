def read(path):
    return json.loads((ROOT / path).read_text())

def write(path, content):
    (ROOT / path).write_text(content.rstrip() + "\n")

def esc(value):
    return escape(str(value), quote=True)

def link(path, label):
    return f'<a href="{esc(path)}">{esc(label)}</a>'

def items(values):
    return '<ul>' + ''.join(f'<li>{value}</li>' for value in values) + '</ul>'

def pairs(values):
    return '<dl>' + ''.join(f'<dt>{esc(key)}</dt><dd>{esc(value)}</dd>' for key, value in values if value) + '</dl>'

