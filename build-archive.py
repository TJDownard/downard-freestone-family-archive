def citations(keys):
    return '<p class="sources">Sources · ' + ' · '.join(link('archive.html#' + key, sources[key]['title']) for key in dict.fromkeys(keys)) + '</p>' if keys else ''

def chip(label):
    caution = ' caution' if label in {'Conflicting','Unverified','Research in progress','Probable'} else ''
    return f'<span class="chip{caution}">{esc(label)}</span>'

