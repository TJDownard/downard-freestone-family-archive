def filter_form(label='Search these records', **options):
    controls = ''.join(
        f'<label>{esc(caption)}<select name="{esc(key)}"><option value="">All</option>' +
        ''.join(f'<option value="{esc(value)}">{esc(text)}</option>' for value, text in choices) +
        '</select></label>' for key, (caption, choices) in options.items())
    return f'<form class="filters" data-filters role="search"><label>{esc(label)}<input type="search" name="q" autocomplete="off"></label>{controls}</form><p class="result-count" role="status" data-count></p>'

def attrs(search, **facets):
    attributes = ''.join(f' data-{name}="{esc(value)}"' for name, value in facets.items())
    return f'data-record data-search="{esc(search)}"{attributes}'

def choices(values):
    return [(value, value) for value in sorted(set(values)) if value]

def records(blocks):
    return '<div class="records">\n' + '\n'.join(blocks) + '\n</div>'

def paragraph(label, html):
    return f'<p><strong>{esc(label)}</strong> {html}</p>' if html else ''

def is_living(person):
    return 'Living' in person['dates'] or 'Present' in person['dates']

def searchable_person(person):
    return ' '.join([person['name'], person['dates'], person.get('birth',''), person.get('death',''),
                     person.get('story',''), person.get('text',''), *person.get('aliases', []),
                     *person.get('occupations', []), *(places[p]['name'] for p in person.get('places', []))])

def event_dates(record):
    return pairs([
        ('Event date', record.get('date')),
        ('Competing event dates', ' or '.join(record.get('dateOptions', []))),
        ('Estimated event date', record.get('estimated')),
        ('Source publication date', record.get('publication')),
        ('Record creation date', record.get('created'))
    ])

def person_details(person):
    key = person['id']
    living = is_living(person)
    children = [p['id'] for p in people.values() if key in p['parents']]
    relation_html = []
    for rel in data['relationships']:
        if key not in (rel['from'], rel['to']):
            continue
        other = rel['to'] if key == rel['from'] else rel['from']
        label = 'Stepparent' if rel['type'] == 'Stepchild' and key == rel['to'] else rel['type']
        relation_html.append(f'<li><strong>{esc(label)}</strong> · {person_links([other])}'
                             + (f' · {chip(rel["status"])}' if rel.get('status') else '')
                             + event_dates(rel) + citations(rel.get('sources')) + '</li>')
    case_links = [link('research.html#' + case['id'], case['title']) for case in cases if key in case['people']]
    property_links = [link('places.html#' + prop['id'], prop['name']) for prop in data['properties'] if key in prop['people']]
    event_links = [link('timeline.html#' + event['id'], event['title']) for event in data['events'] if key in event.get('people', [])]
    story_links = [link('stories.html#' + story['id'], story['title']) for story in data['stories'] if key in story['people']]
    life = pairs([('Names in the records', ', '.join(person.get('aliases', []))), ('Born', person.get('birth')),
                  ('Died', person.get('death')), ('Burial', person.get('burial')),
                  ('Occupations', ', '.join(person.get('occupations', [])))]) if not living else ''
    narrative = ''.join(f'<p>{esc(text)}</p>' for text in dict.fromkeys([person.get('story'), person.get('text'), person.get('notes')]) if text)
    family = (paragraph('Parents', person_links(person['parents'])) + paragraph('Spouses and partners', person_links(person['spouses']))
              + paragraph('Children', person_links(children)))
    if relation_html:
        family += '<ul>' + ''.join(relation_html) + '</ul>'
    related = ''.join([paragraph('Places', place_links(person.get('places', []))),
                       paragraph('Properties', ' · '.join(property_links)),
                       paragraph('Timeline', ' · '.join(event_links)),
                       paragraph('Stories', ' · '.join(story_links)),
                       paragraph('Research questions', ' · '.join(case_links))])
    return f'<div class="reading">{life}{narrative}{family}{related}{citations(person["sources"])}</div>'

