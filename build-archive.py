def filter_form(label='Search these records', **options):
    controls = ''.join(
        f'<label>{esc(caption)}<select name="{esc(key)}"><option value="">All</option>' +
        ''.join(f'<option value="{esc(value)}">{esc(text)}</option>' for value, text in choices) +
        '</select></label>' for key, (caption, choices) in options.items())
    return f'<form class="filters" data-filters role="search"><label>{esc(label)}<input type="search" name="q" autocomplete="off"></label>{controls}</form><p class="result-count" role="status" data-count></p>'

def attrs(search, **facets):
    attributes = ''.join(f' data-{name}="{esc(value)}"' for name, value in facets.items())
    return f'data-record data-search="{esc(search)}"{attributes}'

def choices(values):
    return [(value, value) for value in sorted(set(values)) if value]

def records(blocks):
    return '<div class="records">\n' + '\n'.join(blocks) + '\n</div>'

def paragraph(label, html):
    return f'<p><strong>{esc(label)}</strong> {html}</p>' if html else ''

def is_living(person):
    return person.get('private', False) or 'Living' in person['dates'] or 'Present' in person['dates']

def searchable_person(person):
    return ' '.join([person['name'], person['dates'], person.get('birth',''), person.get('death',''),
                     person.get('story',''), person.get('text',''), *person.get('aliases', []),
                     *person.get('occupations', []), *(places[p]['name'] for p in person.get('places', []))])

def event_dates(record):
    return pairs([
        ('Event date', record.get('date')),
        ('Competing event dates', ' or '.join(record.get('dateOptions', []))),
        ('Estimated event date', record.get('estimated')),
        ('Source publication date', record.get('publication')),
        ('Record creation date', record.get('created'))
    ])

def person_details(person):
    key = person['id']
    living = is_living(person)
    rels = relatives[key]
    relation_html = []
