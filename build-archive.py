def sort_event(event):
    return (event.get('date') or next(iter(event.get('dateOptions', [])), '') or event.get('estimated')
            or event.get('publication') or event.get('created') or '9999')

def event_period(event):
    years = re.findall(r'\b\d{4}\b', sort_event(event))
    return f'{years[0][:2]}00s' if years and years[0] != '9999' else 'Undated'

